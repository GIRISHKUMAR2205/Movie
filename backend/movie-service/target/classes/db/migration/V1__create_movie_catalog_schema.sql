CREATE TABLE movies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by VARCHAR(255) NOT NULL,
    modified_by VARCHAR(255) NOT NULL,
    title VARCHAR(250) NOT NULL,
    synopsis TEXT NOT NULL,
    original_language VARCHAR(80) NOT NULL,
    duration_minutes INTEGER NOT NULL CHECK (duration_minutes > 0),
    certification VARCHAR(20) NOT NULL,
    release_date DATE,
    director VARCHAR(160),
    poster_url VARCHAR(2048),
    trailer_url VARCHAR(2048),
    has_subtitles BOOLEAN NOT NULL,
    published BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE movie_formats (
    movie_id BIGINT NOT NULL REFERENCES movies(id) ON DELETE CASCADE,
    format VARCHAR(60) NOT NULL,
    PRIMARY KEY (movie_id, format)
);
CREATE TABLE movie_subtitle_languages (
    movie_id BIGINT NOT NULL REFERENCES movies(id) ON DELETE CASCADE,
    language VARCHAR(80) NOT NULL,
    PRIMARY KEY (movie_id, language)
);
CREATE TABLE movie_genres (
    movie_id BIGINT NOT NULL REFERENCES movies(id) ON DELETE CASCADE,
    genre VARCHAR(80) NOT NULL,
    PRIMARY KEY (movie_id, genre)
);
CREATE TABLE movie_cast_members (
    movie_id BIGINT NOT NULL REFERENCES movies(id) ON DELETE CASCADE,
    cast_member VARCHAR(160) NOT NULL,
    PRIMARY KEY (movie_id, cast_member)
);

CREATE INDEX ix_movies_published_release_date ON movies (published, release_date DESC);
